"""Writes Sources/Jinja/HTMLEntities.swift from Python's HTML5 entity table.

The `striptags` filter decodes entities with this table,
as Jinja2 does through MarkupSafe and Python's `html.unescape`.

Run from the repository root:

    uv run Tools/generate_html_entities.py
"""

from html.entities import html5
from pathlib import Path


def swift_literal(text):
    out = []
    for char in text:
        if char in '"\\':
            out.append("\\" + char)
        elif 0x20 <= ord(char) < 0x7F:
            out.append(char)
        else:
            out.append(f"\\u{{{ord(char):X}}}")
    return '"' + "".join(out) + '"'


lines = [
    "// Generated by Tools/generate_html_entities.py from Python's html.entities.html5.",
    "// Do not edit by hand.",
    "",
    "/// The HTML5 named character references, keyed by name.",
    "/// Names that end in a semicolon are the standard forms;",
    "/// the others are the legacy names that HTML also accepts without one.",
    "let htmlEntities: [String: String] = [",
]
lines += [f"    {swift_literal(name)}: {swift_literal(value)}," for name, value in sorted(html5.items())]
lines += ["]", ""]
Path("Sources/Jinja/HTMLEntities.swift").write_text("\n".join(lines))
